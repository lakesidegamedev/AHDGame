/**
 * Fit the 2027 US per-state position surface so each state's census
 * electorate economic lean equals LEAN_PER_MARGIN_POINT times its 2024
 * Republican margin. One level L per state: white at L; non-college,
 * middle-income and senior at L + 0.5.
 *
 * Usage: npx tsx scripts/seeds/fit-us-state-positions-2027.ts > src/lib/countries/us/data/usStatePositions2027.ts
 */
import { stateCensusData2023 } from "@/lib/countries/us/data/usStateCensusData2023";
import { stateCensusData2027 } from "@/lib/countries/us/data/usStateCensusData2027";
import { ELECTION_2024_MARGIN } from "@/lib/data/2024ElectionResults";
import { LEAN_PER_MARGIN_POINT } from "@/lib/countries/us/data/usStatePositions2027Target";
import { censusStateLean } from "@/lib/demographics/censusLean";
import { clearGranularElectorateCache } from "@/lib/demographics/granularElectorate";
import type { Layer1Config } from "@/lib/seeds/stateDemographics";

type Positions = NonNullable<Layer1Config["positions"]>;

function surface(level: number, ideology: Positions["ideology"] | undefined): Positions {
  const at = (v: number) => ({ economicLean: round(v), socialLean: round(v) });
  return {
    race: { white: at(level) },
    ...(ideology ? { ideology } : {}),
    education: { no_college: at(level + 0.5) },
    wealth: { middle: at(level + 0.5) },
    age: { senior: at(level + 0.5) },
  };
}

function round(v: number): number {
  return Math.round(v * 100) / 100;
}

function leanAt(stateId: string, positions: Positions): number {
  stateCensusData2027[stateId].positions = positions;
  clearGranularElectorateCache();
  return censusStateLean({ _id: stateId, countryId: "US" } as never, {
    countryId: "US",
    stateId,
    preset: "2027-default",
    year: 2027,
    startingYear: 2027,
  }).economicLean;
}

const out: Record<string, Positions> = {};
const report: string[] = [];
for (const stateId of Object.keys(stateCensusData2027).sort()) {
  // ELECTION_2024_MARGIN is Democratic minus Republican; lean is right-positive.
  const demMargin = ELECTION_2024_MARGIN[stateId];
  const margin = demMargin === undefined ? undefined : -demMargin;
  if (margin === undefined) throw new Error(`No 2024 margin for ${stateId}`);
  const target = LEAN_PER_MARGIN_POINT * margin;
  const ideology = stateCensusData2023[stateId]?.positions?.ideology;
  let lo = -5;
  let hi = 4.5;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (leanAt(stateId, surface(mid, ideology)) < target) lo = mid;
    else hi = mid;
  }
  const level = round((lo + hi) / 2);
  out[stateId] = surface(level, ideology);
  const got = leanAt(stateId, out[stateId]);
  report.push(
    `${stateId} margin ${margin} target ${target.toFixed(2)} level ${level} lean ${got.toFixed(2)}`
  );
}
console.error(report.join("\n"));

console.log(`import type { Layer1Config } from "@/lib/seeds/stateDemographics";

/**
 * 2027 US per-state position surface, fitted so each state's census electorate
 * reproduces its 2024 presidential margin. Generated by
 * scripts/seeds/fit-us-state-positions-2027.ts; regenerate rather than edit.
 */
export const usStatePositions2027: Record<string, NonNullable<Layer1Config["positions"]>> = ${JSON.stringify(out, null, 2)};
`);
