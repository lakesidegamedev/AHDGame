#!/usr/bin/env node
/**
 * Compiles the static landing page's stylesheet: Tailwind over the page
 * renderer's class names, the app's theme tokens, and a few page-only rules.
 * The result is inlined in the page, so it never costs a request.
 *
 *   node scripts/landing/build-landing-css.mjs [--check]
 *
 * `--check` exits 1 when the committed output differs, which the freshness test
 * uses. Regenerate and commit after changing the renderer's classes or the
 * theme tokens in src/app/globals.css.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";
import { transform } from "esbuild";
import * as prettier from "prettier";

const root = process.cwd();
const OUT = path.join(root, "src/lib/landing/static/staticLandingCss.generated.ts");

/** The top-level block that opens with `selector` in globals.css. */
function block(source, selector) {
  const start = source.indexOf(selector);
  if (start < 0) throw new Error(`globals.css has no ${selector}`);
  let depth = 0;
  for (let i = source.indexOf("{", start); i < source.length; i++) {
    if (source[i] === "{") depth++;
    if (source[i] === "}" && --depth === 0) return source.slice(start, i + 1);
  }
  throw new Error(`unterminated ${selector}`);
}

export async function compileLandingCss() {
  const globals = await readFile(path.join(root, "src/app/globals.css"), "utf8");
  const theme = [
    block(globals, ':root,\n[data-theme="default"]'),
    block(globals, "@theme static"),
    block(globals, "@theme inline"),
    block(globals, ".scrollbar-hide {"),
    block(globals, ".scrollbar-hide::-webkit-scrollbar"),
    block(globals, ".ahd-bc-headline"),
    block(globals, ".ahd-bc-odometer {"),
  ].join("\n");
  const input = `
@import "tailwindcss" source(none);
@source "../../src/lib/landing/static/renderLanding.ts";
@source "../../src/landing-islands/globe.ts";
${theme}
@font-face{font-family:Geist;font-style:normal;font-weight:100 900;font-display:swap;src:url(/landing/fonts/geist-latin.woff2) format("woff2");unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}
@font-face{font-family:Geist Mono;font-style:normal;font-weight:100 900;font-display:swap;src:url(/landing/fonts/geist-mono-latin.woff2) format("woff2");unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}
@font-face{font-family:Geist Fallback;src:local(Arial);ascent-override:95.94%;descent-override:28.16%;line-gap-override:0%;size-adjust:104.76%}
@font-face{font-family:Geist Mono Fallback;src:local(Arial);ascent-override:74.67%;descent-override:21.92%;line-gap-override:0%;size-adjust:134.59%}
:root{--font-geist-sans:"Geist","Geist Fallback";--font-geist-mono:"Geist Mono","Geist Mono Fallback"}
html{overflow-x:clip}
body{overflow-x:clip;padding-left:env(safe-area-inset-left,0px);padding-right:env(safe-area-inset-right,0px);background:var(--background);color:var(--foreground);font-family:var(--font-sans),system-ui,sans-serif}
html[data-cookie-consent] [data-cookie-consent-banner]{display:none}
.roster:has(.roster-group:hover) .roster-group:not(:hover){opacity:.4}
`;
  const result = await postcss([tailwind()]).process(input, {
    from: path.join(root, "scripts/landing/landing.css"),
  });
  const minified = await transform(result.css, { loader: "css", minify: true });
  return minified.code.trim();
}

export async function renderLandingCssModule() {
  const css = await compileLandingCss();
  const raw = `// Generated by scripts/landing/build-landing-css.mjs. Do not edit.\nexport const STATIC_LANDING_CSS =\n  ${JSON.stringify(css)};\n`;
  const config = (await prettier.resolveConfig(OUT)) ?? {};
  return { css, body: await prettier.format(raw, { ...config, filepath: OUT }) };
}

async function main() {
  const { css, body } = await renderLandingCssModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUT, "utf8").catch(() => "");
    if (current !== body) {
      console.error("Static landing CSS is stale: run node scripts/landing/build-landing-css.mjs");
      process.exit(1);
    }
  } else {
    await writeFile(OUT, body);
    console.log(`wrote ${OUT} (${css.length} bytes)`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
