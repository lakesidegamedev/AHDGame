#!/usr/bin/env node
/**
 * Bundles the static landing page's three plain-JS islands from
 * src/landing-islands into public/landing/js with content hashes, and writes
 * the manifest the page renderer reads.
 *
 *   node scripts/landing/build-landing-islands.mjs [--check]
 *
 * `--check` builds in memory and exits 1 when the committed files differ, which
 * the freshness test uses. Run it without the flag and commit the outputs
 * after changing an island or anything it imports.
 */
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = process.cwd();
const OUT_DIR = path.join(root, "public/landing/js");
const MANIFEST = path.join(root, "src/lib/landing/static/islandManifest.generated.ts");
const NAMES = ["countdown", "consent", "globe"];

export async function buildIslands() {
  const result = await build({
    entryPoints: Object.fromEntries(
      NAMES.map((name) => [name, path.join(root, "src/landing-islands", `${name}.ts`)])
    ),
    bundle: true,
    write: false,
    minify: true,
    format: "iife",
    target: "es2020",
    platform: "browser",
    legalComments: "none",
    tsconfig: path.join(root, "tsconfig.json"),
    outdir: "out",
    logLevel: "error",
  });
  const files = {};
  for (const file of result.outputFiles) {
    const name = path.basename(file.path, ".js");
    const hash = createHash("sha256").update(file.contents).digest("hex").slice(0, 10);
    files[name] = { fileName: `${name}.${hash}.js`, contents: Buffer.from(file.contents) };
  }
  const manifest = `// Generated by scripts/landing/build-landing-islands.mjs. Do not edit.\nexport const LANDING_ISLANDS = {\n${NAMES.map(
    (name) => `  ${name}: "/landing/js/${files[name].fileName}",`
  ).join("\n")}\n};\n`;
  return { files, manifest };
}

async function main() {
  const { files, manifest } = await buildIslands();
  if (process.argv.includes("--check")) {
    const present = new Set(await readdir(OUT_DIR).catch(() => []));
    const expected = Object.values(files).map((file) => file.fileName);
    const stale =
      (await readFile(MANIFEST, "utf8").catch(() => "")) !== manifest ||
      expected.some((name) => !present.has(name)) ||
      [...present].some((name) => !expected.includes(name));
    if (stale) {
      console.error(
        "Landing islands are stale: run node scripts/landing/build-landing-islands.mjs"
      );
      process.exit(1);
    }
  } else {
    await rm(OUT_DIR, { recursive: true, force: true });
    await mkdir(OUT_DIR, { recursive: true });
    for (const file of Object.values(files)) {
      await writeFile(path.join(OUT_DIR, file.fileName), file.contents);
    }
    await writeFile(MANIFEST, manifest);
    for (const file of Object.values(files)) console.log(file.fileName, file.contents.length);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
