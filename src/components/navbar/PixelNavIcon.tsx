export type PixelNavIconName = keyof typeof SHAPES;

/** The 11x11 bitmap of an icon, rows of "0" and "1". The phone dock API sends these. */
export function pixelNavIconGrid(name: PixelNavIconName): readonly string[] {
  return SHAPES[name];
}

export function PixelNavIcon({
  name,
  className = "h-5 w-5",
}: {
  name: PixelNavIconName;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 11 11"
      className={className}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {SHAPES[name].flatMap((row, y) =>
        [...row].flatMap((bit, x) =>
          bit === "1" ? [<rect key={`${x}:${y}`} x={x} y={y} width={1} height={1} />] : []
        )
      )}
    </svg>
  );
}
