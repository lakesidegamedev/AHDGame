import { correctCpcPurgeAvailability } from "@/lib/seeds/wiki/content/cpcPurgeAvailability";
import { wikiPagesCollection } from "@/lib/db/repositories/wikiPages";
import type { Migration } from "../types";
export const migration: Migration = {
  id: "2026-11-26-cn-wiki-purge-availability",
  description:
    "Label disabled CPC purges and remove unavailable-action advice from authored wiki pages.",
  idempotent: true,
  async execute(db, { dryRun }) {
    const pages = await wikiPagesCollection(db)
      .find(
        {
          slug: { $in: ["china-overview", "china-cpc-confidence"] },
          isAutoGenerated: { $ne: true },
        },
        { projection: { content: 1 } }
      )
      .toArray();
    let updated = 0;
    for (const page of pages) {
      const content = correctCpcPurgeAvailability(page.content);
      if (dryRun || content === page.content) continue;
      const result = await wikiPagesCollection(db).updateOne(
        { _id: page._id, content: page.content },
        { $set: { content, updatedAt: new Date() } }
      );
      if (result.matchedCount !== 1) throw new Error("China wiki update raced with an edit");
      updated += result.modifiedCount;
    }
    return { documentsScanned: pages.length, documentsUpdated: updated };
  },
};
