import { correctCorporationsMargins } from "@/lib/seeds/wiki/content/corporationsMargins";
import { wikiPagesCollection } from "@/lib/db/repositories/wikiPages";
import type { Migration } from "../types";

export const migration: Migration = {
  id: "2026-11-20-corporations-wiki-margins",
  description: "Correct the authored Corporations wiki page's explanation of plant margins.",
  idempotent: true,
  async execute(db, { dryRun }) {
    const pages = wikiPagesCollection(db);
    const authored = { slug: "corporations", isAutoGenerated: { $ne: true } };
    const page = await pages.findOne(authored, { projection: { content: 1 } });
    if (!page) return { documentsScanned: 0, documentsUpdated: 0 };

    const content = correctCorporationsMargins(page.content);
    if (dryRun || content === page.content) return { documentsScanned: 1, documentsUpdated: 0 };

    const update = await pages.updateOne(
      { ...authored, _id: page._id, content: page.content },
      { $set: { content, updatedAt: new Date() } }
    );
    if (!update.matchedCount) throw new Error("Corporations wiki update raced with an edit");
    return { documentsScanned: 1, documentsUpdated: update.modifiedCount };
  },
};
