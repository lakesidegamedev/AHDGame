import { expect, it, vi } from "vitest";
import type { Db } from "mongodb";
import { corporationsContent } from "@/lib/seeds/wiki/content/corporations";
import { createInMemoryDb } from "@/lib/test-utils/inMemoryDb";
import { MIGRATIONS } from "../registry";
import { runMigrations } from "../runner";

const live = `## Profit margin modifiers
Many factors adjust your sector profit margins. These are additive:
| Effective margin | Capped display output derived from the realized profit basis |
| Net profit | The plants P&L result after revenue and all recorded costs |
| Sector type match | +5pp primary / +2.5pp secondary / -15pp unrelated | Bonus if sector matches primary type; penalty if neither type matches |
| Secondary type match | +2.5pp | If sector matches secondary type |
| Commodity input costs | ±50pp per commodity (soft cap) | Logarithmic; shortages in inputs you consume compress margins |
| Commodity output demand | ±50pp per commodity (soft cap) | Logarithmic; shortages in commodities you sell boost margins |
Sectors that don't match your primary or secondary type receive a **-15% penalty**.
3. **Revenue and margin.** Realized revenue is set from what actually sold, then the effective margin applies every modifier below`;
const editorial = "## Editor's notes\n| Local example | Keep this row |";
const stale =
  /every modifier below|These are additive:|Capped display output|lose 15 margin points|move its margin, capped at 8 points|-15% penalty|percentage-point operating margin bonus|nameplate x margin|-15pp unrelated|Logarithmic/;

it("seeds the plants margin explanation", () => {
  expect(corporationsContent).not.toMatch(stale);
  expect(corporationsContent).toContain("below -100%");
  expect(corporationsContent).toContain("N/A when site revenue is zero");
});

it("patches only the authored article, retries an edit conflict, and is idempotent", async () => {
  const memory = createInMemoryDb();
  const db = memory as unknown as Db;
  const pages = memory.collection("wikiPages");
  memory.seed("wikiPages", [
    { _id: "authored", slug: "corporations", content: live },
    { _id: "generated", slug: "corporations", content: live, isAutoGenerated: true },
    { _id: "other", slug: "other", content: live },
  ]);
  const id = "2026-11-20-corporations-wiki-margins";
  const run = (force = false) =>
    runMigrations(db, { migrations: MIGRATIONS, only: [id], dryRun: false, force });
  const update = pages.updateOne.bind(pages);
  const write = vi.spyOn(pages, "updateOne");
  write.mockImplementationOnce(async (filter, change) => {
    await update({ _id: "authored" }, { $set: { content: live + "\n" + editorial } });
    return update(filter, change);
  });
  await expect(run()).rejects.toThrow("raced with an edit");
  expect(memory.collection("migrationsRun").docs).toHaveLength(0);
  expect((await run()).results[id].documentsUpdated).toBe(1);
  const content = (await pages.findOne({ _id: "authored" }))?.content;
  expect(content).not.toMatch(stale);
  expect(content).toContain("## Profit margin modifiers");
  expect(content).toContain(editorial);
  expect((await pages.findOne({ _id: "generated" }))?.content).toBe(live);
  expect((await pages.findOne({ _id: "other" }))?.content).toBe(live);
  expect((await run(true)).results[id].documentsUpdated).toBe(0);
  expect(write).toHaveBeenCalledTimes(2);
});
