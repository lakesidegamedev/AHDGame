import { expect, it, vi } from "vitest";
import { createInMemoryDb } from "@/lib/test-utils/inMemoryDb";
import { seedCNWiki } from "@/lib/admin/seed/seedCNWiki";
import { migration } from "./2026-11-26-cn-wiki-purge-availability";
import {
  REQUIRED_STARTUP_MIGRATIONS,
  REQUIRED_STARTUP_INDEX_MIGRATIONS,
} from "../startupMigrations";
import { MIGRATIONS } from "../registry";
const legacy =
  "### Purges\n\nPurges are internal CPC disciplinary actions. They remove disloyal officials but cost confidence:\n\n- Time purges carefully. Never purge when confidence is already below 60.\n- Process purges quickly. The -2/turn backlog compounds fast.";
it("seeds and deploys the unavailable-action correction without treating it as index repair", async () => {
  expect(MIGRATIONS).toContain(migration);
  expect(REQUIRED_STARTUP_MIGRATIONS).toContain(migration);
  expect(REQUIRED_STARTUP_INDEX_MIGRATIONS).not.toContain(migration);
  const db = createInMemoryDb();
  await seedCNWiki(db as never);
  const confidence = db
    .collection("wikiPages")
    .docs.find((row) => row.slug === "china-cpc-confidence");
  expect(confidence?.content).toContain("Party purges are currently disabled");
  expect(confidence?.content).not.toContain("Time purges carefully");
});
it("dry-runs without writes, preserves editorial text and publication state, and safely repeats", async () => {
  const db = createInMemoryDb();
  db.seed("wikiPages", [
    {
      _id: "authored",
      slug: "china-cpc-confidence",
      content: legacy + "\nEditor note",
      status: "draft",
      viewCount: 42,
    },
    { _id: "generated", slug: "china-overview", content: legacy, isAutoGenerated: true },
  ]);
  await migration.execute(db as never, { dryRun: true });
  expect(db.collection("wikiPages").docs[0].content).toBe(legacy + "\nEditor note");
  expect((await migration.execute(db as never, { dryRun: false })).documentsUpdated).toBe(1);
  expect((await migration.execute(db as never, { dryRun: false })).documentsUpdated).toBe(0);
  expect(db.collection("wikiPages").docs[0]).toMatchObject({ status: "draft", viewCount: 42 });
  expect(db.collection("wikiPages").docs[0].content).toContain("Editor note");
  expect(db.collection("wikiPages").docs[1].content).toBe(legacy);
});
it("an intervening editor wins the compare-and-set and a retry retains their edit", async () => {
  const db = createInMemoryDb();
  db.seed("wikiPages", [{ _id: "authored", slug: "china-cpc-confidence", content: legacy }]);
  const collection = db.collection("wikiPages"),
    update = collection.updateOne.bind(collection);
  vi.spyOn(collection, "updateOne").mockImplementationOnce(async (filter, change) => {
    await update({ _id: "authored" }, { $set: { content: legacy + "\nNew editorial note" } });
    return update(filter, change);
  });
  await expect(migration.execute(db as never, { dryRun: false })).rejects.toThrow(
    "raced with an edit"
  );
  await migration.execute(db as never, { dryRun: false });
  expect(collection.docs[0].content).toContain("New editorial note");
});
