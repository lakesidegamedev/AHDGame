import { wikiPagesCollection } from "@/lib/db/repositories/wikiPages";
import type { Migration } from "../types";

const stalePublishedLeadership =
  "The party starts with **vacant leadership**: its first leadership elections open immediately and end on the same shared cycle as every other party's, so declare your candidacy on the party page.";
const staleSeedElectionTiming =
  "Those leadership elections open immediately and end on the same shared cycle as every other party's, so your co-founders can declare on the party page.";

const founderLeadership =
  "You (the proposer) are seated as the party's first chair; the **vice-chair and treasurer seats start vacant**.";
const electionTiming =
  "During the pre-iteration founding phase, 12-turn elections open only for vacant leadership seats. In regular play, the vice-chair and treasurer elections open immediately and join your country's shared cycle. While the founding chair holds office, the first regular chair election waits until at least one of those two elections has completed. Declare your candidacy on the party page when an election opens.";

export const migration: Migration = {
  id: "2026-11-19-faq-party-leadership",
  description: "Correct the party leadership passage in the published FAQ.",
  idempotent: true,
  async execute(db, ctx) {
    const pages = wikiPagesCollection(db);
    const eligible = {
      slug: "faq",
      status: "published" as const,
      private: { $ne: true },
      isAutoGenerated: { $ne: true },
    };
    const projection = { _id: 1, content: 1 };
    let page = await pages.findOne(eligible, { projection });
    if (!page) return { documentsScanned: 0, documentsUpdated: 0 };

    const target = { ...eligible, _id: page._id };
    for (let attempt = 0; page; attempt++) {
      const content = page.content
        .replace(stalePublishedLeadership, `${founderLeadership} ${electionTiming}`)
        .replace(staleSeedElectionTiming, electionTiming);
      if (content === page.content || ctx.dryRun) break;

      // After the last miss, only ask for a retry if the eligible page still needs the fix.
      if (attempt === 2) throw new Error("FAQ party leadership update raced with edits; retry");

      const result = await pages.updateOne(
        { ...target, content: page.content },
        { $set: { content, updatedAt: new Date() } }
      );
      if (result.matchedCount)
        return { documentsScanned: 1, documentsUpdated: result.modifiedCount };

      page = await pages.findOne(target, { projection });
    }

    return { documentsScanned: 1, documentsUpdated: 0 };
  },
};
