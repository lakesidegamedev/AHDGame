import type { Db } from "mongodb";
import { describe, expect, it, vi } from "vitest";
import { faqContent } from "@/lib/seeds/wiki/content/faq";
import { createInMemoryDb } from "@/lib/test-utils/inMemoryDb";
import { migration } from "./2026-11-21-faq-party-leadership";

const paragraphStart =
  "You draft a **Party Charter** on the new-charter page: name, abbreviation, an economic and social platform, and three human founders (yourself plus two others). Your two co-founders must live in your home state or a state adjacent to it, since a new party's founding trio is geographically anchored, just like its founding NPP cohort. Once all three founders sign on the charter's page, the charter ratifies, the party is created, and all three founders are joined to it as members.";
const paragraphEnd =
  "Your new party has zero state org, so building that from zero takes time. See [Political Parties](/wiki/political-parties) for the full charter lifecycle (rejections, founder replacement, expiry).";
const productionPassage = [
  paragraphStart,
  "The party starts with **vacant leadership**: its first leadership elections open immediately and end on the same shared cycle as every other party's, so declare your candidacy on the party page.",
  paragraphEnd,
].join(" ");
const partialPassage = [
  paragraphStart,
  "You (the proposer) are seated as the party's first chair; the **vice-chair and treasurer seats start vacant**. Those leadership elections open immediately and end on the same shared cycle as every other party's, so your co-founders can declare on the party page.",
  paragraphEnd,
].join(" ");
const correctedPassage = [
  paragraphStart,
  "You (the proposer) are seated as the party's first chair; the **vice-chair and treasurer seats start vacant**.",
  "During the pre-iteration founding phase, 12-turn elections open only for vacant leadership seats. In regular play, the vice-chair and treasurer elections open immediately and join your country's shared cycle. While the founding chair holds office, the first regular chair election waits until at least one of those two elections has completed. Declare your candidacy on the party page when an election opens.",
  paragraphEnd,
].join(" ");

function setup(content = productionPassage, attributes = {}) {
  const memory = createInMemoryDb();
  memory.seed("wikiPages", [
    { _id: "faq", slug: "faq", status: "published", content, ...attributes },
    { _id: "other", slug: "other", status: "published", content: productionPassage },
  ]);
  const db = memory as unknown as Db;
  const pages = memory.collection("wikiPages");
  const readFaq = () => pages.findOne({ _id: "faq" });
  return { db, pages, readFaq };
}

describe("FAQ party leadership migration", () => {
  it("updates the exact published passage and preserves surrounding content", async () => {
    const { db, pages, readFaq } = setup(
      `Before the paragraph\n\n${productionPassage}\n\nAfter it`
    );
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(1);
    expect((await readFaq())?.content).toBe(
      `Before the paragraph\n\n${correctedPassage}\n\nAfter it`
    );
    expect((await pages.findOne({ _id: "other" }))?.content).toBe(productionPassage);
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(0);
  });

  it("updates the partial passage without duplicating the founder sentence", async () => {
    const { db, readFaq } = setup(partialPassage);
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(1);
    expect((await readFaq())?.content).toBe(correctedPassage);
  });

  it("seeds the same corrected paragraph", () => {
    expect(faqContent.split("\n\n")).toContain(correctedPassage);
  });

  it("leaves an eligible page untouched on a dry run", async () => {
    const { db, readFaq } = setup();
    const before = await readFaq();
    expect((await migration.execute(db, { dryRun: true })).documentsUpdated).toBe(0);
    expect(await readFaq()).toEqual(before);
  });

  it.each([{ status: "draft" }, { private: true }, { isAutoGenerated: true }])(
    "skips a page with %j",
    async (attributes) => {
      const { db, readFaq } = setup(productionPassage, attributes);
      expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(0);
      expect((await readFaq())?.content).toBe(productionPassage);
    }
  );

  it("leaves rewritten text alone", async () => {
    const { db, readFaq } = setup("An editor rewrote the answer.");
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(0);
    expect((await readFaq())?.content).toBe("An editor rewrote the answer.");
  });

  it("reapplies the replacement to the first concurrent edit", async () => {
    const { db, pages, readFaq } = setup();
    const updateOne = pages.updateOne.bind(pages);
    vi.spyOn(pages, "updateOne").mockImplementationOnce(async (filter, update) => {
      await updateOne({ _id: "faq" }, { $set: { content: `${productionPassage}\nEditor's note` } });
      return updateOne(filter, update);
    });
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(1);
    expect((await readFaq())?.content).toBe(`${correctedPassage}\nEditor's note`);
  });

  it.each([
    {
      name: "already corrected",
      edit: { content: `${correctedPassage}\nSecond edit` },
    },
    {
      name: "no longer eligible",
      edit: { status: "draft", content: `${productionPassage}\nSecond edit` },
    },
  ])("accepts the page after a second miss if it is $name", async ({ edit }) => {
    const { db, pages, readFaq } = setup();
    const updateOne = pages.updateOne.bind(pages);
    const race = vi
      .spyOn(pages, "updateOne")
      .mockImplementationOnce(async (filter, update) => {
        await updateOne({ _id: "faq" }, { $set: { content: `${productionPassage}\nFirst edit` } });
        return updateOne(filter, update);
      })
      .mockImplementationOnce(async (filter, update) => {
        await updateOne({ _id: "faq" }, { $set: edit });
        return updateOne(filter, update);
      });
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(0);
    expect(race).toHaveBeenCalledTimes(2);
    expect(await readFaq()).toMatchObject(edit);
  });

  it("preserves a second concurrent edit and leaves a stale page eligible for retry", async () => {
    const { db, pages, readFaq } = setup();
    const updateOne = pages.updateOne.bind(pages);
    const latest = `${productionPassage}\nEdit 2`;
    let edits = 0;
    const race = vi.spyOn(pages, "updateOne").mockImplementation(async (filter, update) => {
      await updateOne(
        { _id: "faq" },
        { $set: { content: `${productionPassage}\nEdit ${++edits}` } }
      );
      return updateOne(filter, update);
    });
    await expect(migration.execute(db, { dryRun: false })).rejects.toThrow("raced with edits");
    expect(race).toHaveBeenCalledTimes(2);
    expect((await readFaq())?.content).toBe(latest);
    race.mockRestore();
    expect((await migration.execute(db, { dryRun: false })).documentsUpdated).toBe(1);
    expect((await readFaq())?.content).toBe(`${correctedPassage}\nEdit 2`);
  });
});
