/**
 * Which legislation type holds each mechanical law in each country, and the
 * level a country starts at before any bill is passed.
 */
import type { CountryId } from "@/lib/constants/countries";
import { LEGISLATION_COUNTRY_SCOPES } from "@/lib/policy/nationalPolicyRecords";
import { ANTITRUST_LAW_BY_COUNTRY } from "@/lib/corporations/mergerReview/constants";
import { BANKING_SEPARATION_SPECS } from "@/lib/seeds/shared/bankingSeparationLegislation";
import { MECHANICAL_LAW_ID_SUFFIX } from "./legislation";
import type { MechanicalLawKey, MechanicalLawLevel } from "./rules";

/**
 * Starting levels for the generated laws. Competition starts at active merger
 * review, the standard among market economies; the group and foreign rules
 * start open until a legislature acts. Command economies are inert regardless:
 * merger review and the group rules gate on the live marketization dial.
 */
export const MECHANICAL_LAW_BASELINE: Record<MechanicalLawKey, MechanicalLawLevel> = {
  competition: 2,
  subsidiaryLimits: 0,
  foreignInvestment: 0,
};

const PREFIX_BY_SCOPE = new Map(BANKING_SEPARATION_SPECS.map((s) => [s.scope, s.prefix]));

/**
 * Legislation type id for a country's mechanical law, or null when the country
 * has no legislature to pass one. Competition in the four new-generation
 * countries is their existing competition primary.
 */
export function mechanicalLawId(countryId: CountryId, key: MechanicalLawKey): string | null {
  if (key === "competition") {
    const newGeneration = ANTITRUST_LAW_BY_COUNTRY[countryId];
    if (newGeneration) return newGeneration;
  }
  const scope = LEGISLATION_COUNTRY_SCOPES[countryId];
  const prefix = scope ? PREFIX_BY_SCOPE.get(scope) : undefined;
  return prefix ? `${prefix}${MECHANICAL_LAW_ID_SUFFIX[key]}` : null;
}

/** The law key of an id generated by mechanicalLaws/legislation, else null. */
export function mechanicalLawKeyForId(id: string): MechanicalLawKey | null {
  for (const [key, suffix] of Object.entries(MECHANICAL_LAW_ID_SUFFIX)) {
    if (id.endsWith(suffix)) return key as MechanicalLawKey;
  }
  return null;
}
