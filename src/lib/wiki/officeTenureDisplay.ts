import type { OfficeTenureEntry } from "./autoGeneratedPages";

function formatDate(date: Date): string {
  return new Intl.DateTimeFormat("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  }).format(new Date(date));
}

/** A missing historical date must never imply that a former holder still serves. */
export function realLifeDateRange(entry: OfficeTenureEntry): string {
  if (!entry.startDate && !entry.endDate) return "Not recorded";
  const start = entry.startDate ? formatDate(entry.startDate) : "Start date unknown";
  const end = entry.endDate
    ? formatDate(entry.endDate)
    : entry.isCurrent
      ? "Present"
      : "End date unknown";
  return `${start} - ${end}`;
}

export function tenureRangeWeekYear(entry: OfficeTenureEntry): string {
  const start = entry.startWeekYear ?? "Start unknown";
  const end = entry.endWeekYear ?? (entry.isCurrent ? "Incumbent" : "End unknown");
  return `${start} - ${end}`;
}
