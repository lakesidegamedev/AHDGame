import { describe, expect, it } from "vitest";
import { ObjectId, type Db } from "mongodb";
import { createMockDb } from "@/lib/test-utils/mockDb";
import {
  applyPartyLabels,
  getExecutiveHistory,
  type GeneratedOfficeDefinition,
} from "./autoGeneratedPages";
import {
  frozenExecutiveIdentity,
  unrecordedHistoricalParty,
  recordedExecutiveIdentity,
  sameTenureHolder,
} from "./rules/executiveIdentity";

describe("executive wiki election-time identity", () => {
  it("recognizes a renamed legacy NPC by its handover time without merging distinct known holders", () => {
    const startDate = new Date("2026-01-01T00:00:00Z");
    expect(sameTenureHolder({ name: "Old NPC", startDate }, { name: "New NPC", startDate })).toBe(
      true
    );
    expect(
      sameTenureHolder(
        { name: "Name", startDate, profileHref: "/character/1" },
        { name: "Name", startDate, profileHref: "/character/2" }
      )
    ).toBe(false);
  });
  it("uses the finalized winner rather than the first or most popular candidate", () => {
    expect(
      frozenExecutiveIdentity("US", "president", {
        countryId: "US",
        electionType: "president",
        summary: { projectedWinner: "winner" },
        candidates: [
          { id: "loser", name: "Popular vote leader", party: "5", partyName: "Other Party" },
          { id: "winner", name: "Electoral winner", party: "7", partyName: "Original Party" },
        ],
      })?.name
    ).toBe("Electoral winner");
  });

  it("uses an appointment-time snapshot when no direct executive election exists", () => {
    const recorded = recordedExecutiveIdentity({
      officeIdentitySnapshot: {
        name: "Original PM",
        party: "7",
        partyLabel: "Original Party (OLD)",
      },
    });
    expect(recorded?.name).toBe("Original PM");
    expect(
      applyPartyLabels(
        [{ ...recorded!, source: "country-history" }],
        new Map([["7", "New Party"]])
      )[0].partyLabel
    ).toBe("Original Party (OLD)");
    expect(recordedExecutiveIdentity({ officeIdentitySnapshot: "invalid" })).toBeUndefined();
  });
  it.each(["US", "FR", "BR"])("preserves frozen winner and party names in %s", (countryId) => {
    const result = frozenExecutiveIdentity(countryId, "president", {
      countryId,
      electionType: "president",
      summary: { projectedWinner: "winner" },
      candidates: [
        { id: "winner", name: "Election Night Name", party: "7", partyName: "Original Party" },
      ],
    });
    expect(result).toEqual({
      name: "Election Night Name",
      party: "7",
      partyLabel: "Original Party",
    });
    expect(
      applyPartyLabels(
        [{ ...result!, source: "country-history" }],
        new Map([["7", "Renamed Party (NEW)"]])
      )[0].partyLabel
    ).toBe("Original Party");
  });

  it("does not guess an executive from another country's or a parliamentary result", () => {
    const result = {
      countryId: "JP",
      electionType: "shugiin",
      summary: { projectedWinner: "x" },
      candidates: [{ id: "x", name: "Candidate", party: "7", partyName: "Party" }],
    };
    expect(frozenExecutiveIdentity("US", "president", result)).toBeUndefined();
    expect(frozenExecutiveIdentity("JP", "primeMinister", result)).toBeUndefined();
    expect(frozenExecutiveIdentity("US", "president", undefined)).toBeUndefined();
  });

  it("keeps unknown historical party labels explicit rather than using today's party", () => {
    expect(unrecordedHistoricalParty("7")).toBe("Party 7 (historical name unrecorded)");
    expect(unrecordedHistoricalParty("independent")).toBe("Independent");
    expect(unrecordedHistoricalParty("Original Party")).toBe("Original Party");
  });

  it("loads snapshots in one batch and does not append a fake tenure after a profile rename", async () => {
    const db = createMockDb();
    const characterId = new ObjectId(),
      electionId = new ObjectId();
    db.collection("electedOfficials").findOne.mockResolvedValue({
      characterId,
      characterName: "New Profile Name",
      party: "9",
      electedAt: new Date("2026-01-02"),
    });
    db.collection("countryHistory")
      .find()
      .toArray.mockResolvedValue([
        {
          characterId,
          characterName: "Event Name",
          countryId: "US",
          party: "7",
          timestamp: new Date("2026-01-01"),
          turn: 1,
          details: { electionId: electionId.toString() },
        },
        {
          characterId,
          characterName: "Event Name",
          countryId: "US",
          party: "7",
          timestamp: new Date("2026-01-02"),
          turn: 2,
          details: { electionId: electionId.toString() },
        },
      ]);
    db.collection("electionResultSnapshots")
      .find()
      .toArray.mockResolvedValue([
        {
          electionId,
          countryId: "US",
          electionType: "president",
          summary: { projectedWinner: "winner" },
          candidates: [{ id: "winner", name: "Election Name", party: "7", partyName: "Old Party" }],
        },
      ]);
    // Ignore setup calls to the mock cursor.
    db.collectionMocks.electionResultSnapshots.find.mockClear();
    const rows = await getExecutiveHistory(
      db as unknown as Db,
      { countryId: "US", officeType: "president" } as GeneratedOfficeDefinition,
      {
        current: { type: "Iteration", number: 2 },
        startingYear: 1991,
        anchor: { currentTurn: 2, lastTurnProcessed: new Date("2026-01-02"), startingYear: 1991 },
      }
    );
    expect(rows).toHaveLength(2);
    expect(rows.map((row) => [row.name, row.partyLabel])).toEqual([
      ["Election Name", "Old Party"],
      ["Election Name", "Old Party"],
    ]);
    expect(db.collectionMocks.electionResultSnapshots.find).toHaveBeenCalledOnce();
    expect(db.collectionMocks.electionResultSnapshots.find.mock.calls[0][0].electionId.$in).toEqual(
      [electionId]
    );
  });
});
