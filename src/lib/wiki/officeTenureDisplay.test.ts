import { describe, expect, it } from "vitest";
import type { OfficeTenureEntry } from "./autoGeneratedPages";
import { realLifeDateRange, tenureRangeWeekYear } from "./officeTenureDisplay";

const former: OfficeTenureEntry = { name: "Former holder", source: "manual", isCurrent: false };

describe("office tenure dates", () => {
  it("does not call an undated historical tenure incumbent", () => {
    expect(realLifeDateRange(former)).toBe("Not recorded");
    expect(tenureRangeWeekYear(former)).toBe("Start unknown - End unknown");
  });

  it("does not call a dated former holder present when their end date is missing", () => {
    const entry = { ...former, startDate: new Date("2026-01-01T00:00:00Z") };
    expect(realLifeDateRange(entry)).toBe("January 1, 2026 - End date unknown");
  });

  it("uses UTC for stored historical dates and preserves partial ranges", () => {
    expect(realLifeDateRange({ ...former, endDate: new Date("2026-01-02T00:00:00Z") })).toBe(
      "Start date unknown - January 2, 2026"
    );
  });

  it("reserves Present and Incumbent for the actual current holder", () => {
    const entry = {
      ...former,
      isCurrent: true,
      startDate: new Date("2026-01-01T00:00:00Z"),
      startWeekYear: "Week 1, 1991",
    };
    expect(realLifeDateRange(entry)).toBe("January 1, 2026 - Present");
    expect(tenureRangeWeekYear(entry)).toBe("Week 1, 1991 - Incumbent");
  });
});
