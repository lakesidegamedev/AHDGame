// src/lib/wiki/wikiSearch.ts
import type { AutoGeneratedPageKind } from "@/lib/wiki/autoGeneratedPages";
import type { WikiHeading } from "@/lib/wiki/headings";

/**
 * Every surface the wiki search can return. `page` is an authored wiki page
 * from the `wikiPages` collection; the rest are generated or static surfaces
 * that live under /wiki but have no `wikiPages` document behind them. `docs`
 * is the separate engineering docs site.
 */
export type WikiSearchKind = "page" | AutoGeneratedPageKind | "category" | "path" | "docs";

/** A searchable wiki surface before ranking. Match-only fields are stripped from the result. */
export interface WikiSearchCandidate {
  slug: string;
  title: string;
  description?: string;
  href: string;
  kind: WikiSearchKind;
  tags?: string[];
  featured?: boolean;
  /**
   * The source already confirmed the query matched this candidate's body.
   *
   * The database query matches title/description/content itself, so a document
   * it returned whose title and description do not match must have matched on
   * content. Carrying that as a flag lets a body hit rank correctly without
   * projecting whole page bodies over the wire just to re-derive it.
   */
  matchedBody?: boolean;
  /** Section headings, when the caller loaded them, for heading matches and deep links. */
  headings?: WikiHeading[];
}

/** A ranked hit as returned to the client. */
export type WikiSearchResult = Omit<WikiSearchCandidate, "matchedBody" | "headings"> & {
  /** Section anchor (no leading #) the href already points at, when a heading matched. */
  anchor?: string;
};

/**
 * Match tiers, best first. A title hit must always outrank a body hit: searching
 * "filibuster" should surface the Filibuster page, not every page that happens
 * to mention the word.
 */
const SCORE_TITLE_EXACT = 100;
const SCORE_TITLE_PREFIX = 80;
const SCORE_TITLE_SUBSTRING = 60;
const SCORE_HEADING_PHRASE = 55;
const SCORE_HEADING_WORDS = 50;
const SCORE_DESCRIPTION = 40;
const SCORE_TITLE_FUZZY = 35;
const SCORE_CONTENT = 20;
const SCORE_DESCRIPTION_FUZZY = 15;
const SCORE_NO_MATCH = 0;

/** Words this long may differ by one letter and still match. */
const FUZZY_MIN_WORD_LENGTH = 5;

function words(text: string): string[] {
  return text.toLowerCase().match(/[a-z0-9]+/g) ?? [];
}

/** True when a and b are equal or differ by one insertion, deletion or substitution. */
export function withinOneEdit(a: string, b: string): boolean {
  if (a === b) return true;
  const lenDiff = a.length - b.length;
  if (Math.abs(lenDiff) > 1) return false;
  let i = 0;
  let j = 0;
  let edits = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) {
      i++;
      j++;
      continue;
    }
    if (++edits > 1) return false;
    if (lenDiff > 0) i++;
    else if (lenDiff < 0) j++;
    else {
      i++;
      j++;
    }
  }
  return edits + (a.length - i) + (b.length - j) <= 1;
}

function wordMatches(queryWord: string, textWords: string[]): boolean {
  const fuzzy = queryWord.length >= FUZZY_MIN_WORD_LENGTH;
  return textWords.some(
    (w) => w === queryWord || w.startsWith(queryWord) || (fuzzy && withinOneEdit(queryWord, w))
  );
}

/** Every query word appears in the text, with one-letter slack on long words. */
function allWordsMatch(queryWords: string[], text: string): boolean {
  if (queryWords.length === 0) return false;
  const textWords = words(text);
  return queryWords.every((qw) => wordMatches(qw, textWords));
}

/** True when the query has a word long enough to be worth a typo-tolerant pass. */
export function hasFuzzyEligibleWord(query: string): boolean {
  return words(query).some((w) => w.length >= FUZZY_MIN_WORD_LENGTH);
}

interface HeadingMatch {
  score: number;
  heading: WikiHeading;
}

function bestHeadingMatch(q: string, queryWords: string[], headings: WikiHeading[]) {
  let best: HeadingMatch | null = null;
  for (const heading of headings) {
    const text = heading.text.toLowerCase();
    let score = SCORE_NO_MATCH;
    if (text.includes(q)) score = SCORE_HEADING_PHRASE;
    else if (allWordsMatch(queryWords, text)) score = SCORE_HEADING_WORDS;
    // Prefer the tighter heading when scores tie.
    if (score > (best?.score ?? 0)) best = { score, heading };
    else if (best && score === best.score && text.length < best.heading.text.length) {
      best = { score, heading };
    }
  }
  return best;
}

interface Scored {
  score: number;
  anchor?: string;
}

function scoreWikiSearchCandidate(query: string, candidate: WikiSearchCandidate): Scored {
  const q = query.trim().toLowerCase();
  if (!q) return { score: SCORE_TITLE_EXACT };

  const title = candidate.title.toLowerCase();
  if (title === q) return { score: SCORE_TITLE_EXACT };
  if (title.startsWith(q)) return { score: SCORE_TITLE_PREFIX };
  if (title.includes(q)) return { score: SCORE_TITLE_SUBSTRING };

  const queryWords = words(q);
  const heading = candidate.headings ? bestHeadingMatch(q, queryWords, candidate.headings) : null;
  if (heading) return { score: heading.score, anchor: heading.heading.id };

  const description = candidate.description?.toLowerCase() ?? "";
  if (description.includes(q)) return { score: SCORE_DESCRIPTION };
  if (allWordsMatch(queryWords, candidate.title)) return { score: SCORE_TITLE_FUZZY };
  if (candidate.matchedBody) return { score: SCORE_CONTENT };
  if (allWordsMatch(queryWords, description)) return { score: SCORE_DESCRIPTION_FUZZY };
  return { score: SCORE_NO_MATCH };
}

/**
 * Rank candidates by match quality, then alphabetically, and only then apply
 * the limit. Applying the limit first (as an unsorted `find().limit()` does)
 * makes the cutoff arbitrary — an exact title match can be dropped in favour of
 * whichever documents the database happened to return first.
 */
export function rankWikiSearchCandidates(
  query: string,
  candidates: WikiSearchCandidate[],
  limit: number
): WikiSearchResult[] {
  const scored: Array<{ score: number; anchor?: string; candidate: WikiSearchCandidate }> = [];

  for (const candidate of candidates) {
    const { score, anchor } = scoreWikiSearchCandidate(query, candidate);
    if (score === SCORE_NO_MATCH) continue;
    scored.push({ score, anchor, candidate });
  }

  scored.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    return a.candidate.title.localeCompare(b.candidate.title);
  });

  return scored.slice(0, limit).map(({ candidate, anchor }) => {
    const { matchedBody: _matchedBody, headings: _headings, ...result } = candidate;
    void _matchedBody;
    void _headings;
    if (!anchor) return result;
    return { ...result, href: `${result.href}#${anchor}`, anchor };
  });
}
