export const metricContracts = specifications.map(
  ([
    id,
    unit,
    population,
    aggregation,
    politicalMechanism,
    economicMechanism,
    remainingEvidence,
  ]) => {
    const current = primaryMetrics.find((metric) => metric.id === id);
    if (!current) throw new Error(`Metric contract has no catalog entry: ${id}`);
    return {
      id,
      path: current.path,
      owner: current.owner,
      current: { unit: current.unit, refresh: current.refresh, aggregation: current.aggregation },
      target: {
        definitionVersion: 2,
        unit,
        population,
        aggregation,
        politicalMechanism,
        economicMechanism,
        evaluation: "every-turn" as const,
        measurement:
          current.refresh === "cohort"
            ? "cohort"
            : current.refresh === "election"
              ? "election"
              : "owner-window",
        initialization: "reviewed country and era opening; never infer missing flows as zero",
        missingEvidence: "retain source measurement date and label proxy or unavailable",
        bounds: "physical owner bounds; condition-score limits never cap the measured value",
      },
      implementation: "requires-owner-evidence" as const,
      remainingEvidence,
    };
  }
);

/** Review coverage, not a switch that silently upgrades existing countries. */
export function metricCountryCoverage(countryIds: readonly string[]) {
  return [...new Set(countryIds)].sort().map((countryId) => ({
    countryId,
    currentPath: isResetV2Country(countryId) ? "reviewed-v2-catalog" : "legacy",
    targetModelReady: false,
    remaining:
      "review household, fiscal, service and era adapters; qualify migration before activation",
  }));
}
