const SUFFIX = /\s+(jr|sr|ii|iii|iv|v)$/;

function normalize(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[.,'’]/g, "")
    .replace(/[-\s]+/g, " ")
    .trim()
    .replace(SUFFIX, "")
    .trim();
}

const RESERVED: ReadonlySet<string> = new Set(NAMES.map(normalize));

/** True when a generated NPP name is a real politician's or notorious figure's name. */
export function isRealPoliticianName(name: string): boolean {
  return RESERVED.has(normalize(name));
}
