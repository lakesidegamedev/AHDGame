import type { NotificationType } from "@/lib/db/types/notifications";

/**
 * How far an alert reaches. `push` alerts also go to the phone and desktop
 * notification centre; `inbox` alerts wait in the inbox.
 *
 * Push is for things the player has to act on, or a result about them they
 * would want to hear at once: a vote to cast, an offer to answer, a race won
 * or lost, an attack on their company. Routine reports (R&D results, bond
 * schedules, rating moves, contract expiries, crises in the home state) stay
 * in the inbox. Measured 2026-10: those routine types were over 90% of all
 * alerts and almost none were ever opened.
 *
 * Total map: a new NotificationType without a delivery here is a compile
 * error, so every new alert makes this choice on purpose.
 */
