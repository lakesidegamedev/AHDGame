interface WikiPageProps {
  params: Promise<{ slug: string }>;
}

export async function generateMetadata({ params }: WikiPageProps): Promise<Metadata> {
  const { slug } = await params;
  if (getRedirectTarget(slug)) return { title: "Redirect" };
  const page = await getWikiPageData(slug);
  const generatedDefinition = await getGeneratedOfficeDefinition(slug);
  if (!page && !generatedDefinition)
    return { title: "Not found", robots: { index: false, follow: false } };
  if (!page && generatedDefinition) {
    const title = `${generatedDefinition.title} | Game Wiki | A House Divided`;
    const description = generatedDefinition.description;
    const canonical = getWikiCanonicalUrl(`/wiki/${slug}`);
    return {
      title,
      description,
      alternates: { canonical },
      openGraph: {
        title,
        description,
        url: canonical,
        type: "article",
        siteName: "A House Divided",
      },
      twitter: {
        card: "summary",
        title,
        description,
      },
    };
  }
  if (!page) return { title: "Not found", robots: { index: false, follow: false } };
  const title = `${page.title} | Game Wiki | A House Divided`;
  const description = page.description;
  const canonical = getWikiCanonicalUrl(`/wiki/${slug}`);
  // Incomplete community pages stay out of search until the owner adds enough
  // original content to make the page useful on its own.
  const isLowValue = (await getLowValueWikiSlugs()).includes(slug);
  return {
    title,
    description,
    ...(isLowValue ? { robots: { index: false, follow: true } } : {}),
    alternates: { canonical },
    openGraph: {
      title,
      description,
      url: canonical,
      type: "article",
      siteName: "A House Divided",
    },
    twitter: {
      card: "summary",
      title,
      description,
    },
  };
}

async function isPageAuthor(slug: string, userId: string): Promise<boolean> {
  const db = await getDb();
  const page = await wikiPagesCollection<Document>(db).findOne(
    { slug },
    { projection: { submittedBy: 1 } }
  );
  return page?.submittedBy?.toString() === userId;
}

export default async function WikiPage({ params }: WikiPageProps) {
  const { slug } = await params;
  const redirectTo = getRedirectTarget(slug);
  if (redirectTo) redirect(redirectTo);
  if (slug === "elections") notFound();

  const generatedOfficePage = await getGeneratedOfficePageData(slug);
  if (generatedOfficePage) {
    const user = await getAuthUserWithCharacter();
    const editableContent = generatedOfficePage.hasEditableContent
      ? await loadWikiContent(slug)
      : null;
    return (
      <GeneratedOfficeWikiPage
        slug={slug}
        page={generatedOfficePage}
        editableContent={editableContent}
        canEdit={Boolean(user && generatedOfficePage.hasEditableContent)}
        isAdmin={user?.isAdmin === true}
      />
    );
  }

  const page = await getWikiPageData(slug);
  if (!page) notFound();

  const content = await loadWikiContent(slug);
  if (!content) notFound();

  const headings = extractWikiHeadings(content);
  const user = await getAuthUserWithCharacter();
  // Only the page's author and moderators can edit it; everyone else sees no controls.
  const canWrite =
    !!user &&
    (user.isAdmin === true ||
      user.isModerator === true ||
      (await isPageAuthor(slug, user.userId.toString())));

  // Fire-and-forget view count increment
  getDb()
    .then((db) => wikiPagesCollection<Document>(db).updateOne({ slug }, { $inc: { viewCount: 1 } }))
    .catch(() => {});

  // Track wiki visit for onboarding checklist
  if (slug === "getting-started" && user?.character) {
    getDb()
      .then((db) =>
        charactersCollection(db).updateOne(
          { _id: user.character!._id, hasReadWiki: { $ne: true } },
          { $set: { hasReadWiki: true } }
        )
      )
      .catch(() => {});
  }

  return (
    <WikiArticleFrame content={content} headings={headings}>
      <Breadcrumbs items={[{ label: "Wiki", href: "/wiki" }, { label: page.title }]} />

      {canWrite && (
        <div className="mb-4 flex justify-end gap-2">
          <Link
            href={`/wiki/${slug}/history`}
            className="rounded-md bg-card px-3 py-1.5 text-body-sm text-muted transition-colors hover:text-foreground"
          >
            History
          </Link>
          <Link
            href={`/wiki/${slug}/edit`}
            className="rounded-md bg-card px-3 py-1.5 text-body-sm text-muted transition-colors hover:text-foreground"
          >
            Edit page
          </Link>
        </div>
      )}

      <WikiTrustStrip content={content} slug={slug} />

      <PageMetadata
        category={page.category}
        contentType={page.contentType}
        difficulty={page.difficulty}
        estimatedReadTime={page.estimatedReadTime}
        lastUpdated={page.lastUpdated ?? page.updatedAt}
        designDocUrl={page.designDocUrl}
        gameIteration={page.gameIteration}
        gameStartDate={page.gameStartDate}
        reportSlug={slug}
      />

      <article data-wiki-article className="max-w-none overflow-x-clip">
        <WikiWriterProvider isWriter={canWrite}>
          <MarkdownContent content={content} headings={headings} />
        </WikiWriterProvider>
      </article>

      <RelatedPagesFooter
        currentSlug={slug}
        currentCategory={page.category}
        currentTags={page.tags}
      />
    </WikiArticleFrame>
  );
}

function GeneratedOfficeWikiPage({
  slug,
  page,
  editableContent,
  canEdit,
  isAdmin,
}: {
  slug: string;
  page: GeneratedOfficePageData;
  editableContent: string | null;
  canEdit: boolean;
  isAdmin: boolean;
}) {
  const content = editableContent ?? generatedOfficeDefaultContent(page.definition);
  const headings = extractWikiHeadings(content);
  const current = page.currentHolder;

  return (
    <WikiArticleFrame content={content} headings={headings}>
      <Breadcrumbs
        items={[
          { label: "Wiki", href: "/wiki" },
          { label: "Auto-generated pages", href: "/wiki#auto-generated-pages" },
          { label: page.definition.title },
        ]}
      />

      {canEdit && (
        <div className="mb-4 flex justify-end">
          <Link
            href={`/wiki/${slug}/edit`}
            className="rounded-md bg-card px-3 py-1.5 text-body-sm text-muted transition-colors hover:text-foreground"
          >
            Edit article text
          </Link>
        </div>
      )}

      <header className="mb-5">
        <p className="mb-2 text-body-sm font-semibold uppercase tracking-[0.06em] text-muted">
          Generated office page
        </p>
        <h1 className="text-display font-extrabold leading-[1.15] tracking-[-0.03em] text-foreground">
          {page.definition.title}
        </h1>
        <p className="mt-3 max-w-[62ch] text-body-lg leading-[1.6] text-foreground">
          {page.definition.description}
        </p>
      </header>

      <PageMetadata
        category="reference"
        contentType="reference"
        lastUpdated={new Date()}
        reportSlug={slug}
      />

      <article data-wiki-article className="max-w-none overflow-x-clip">
        <MarkdownContent content={content} headings={headings} />
      </article>

      <section className="mt-8">
        <h2 className="mb-3 text-heading font-extrabold tracking-[-0.03em] text-foreground">
          Current holder
        </h2>
        {current ? (
          <div className="border-b border-card-border/60 py-2">
            <div className="flex flex-col gap-1 sm:flex-row sm:items-center sm:justify-between">
              <div>
                {current.profileHref ? (
                  <Link
                    href={current.profileHref}
                    className="font-semibold text-foreground hover:text-primary"
                  >
                    {current.name}
                  </Link>
                ) : (
                  <span className="font-semibold text-foreground">{current.name}</span>
                )}
                {current.partyLabel && (
                  <span className="ml-2 text-body text-muted">({current.partyLabel})</span>
                )}
              </div>
              <div className="font-mono text-body-sm text-muted">
                {tenureRangeWeekYear(current)}
              </div>
            </div>
          </div>
        ) : (
          <div className="py-2">
            <p className="font-medium text-foreground">Vacant or not yet recorded</p>
            <p className="mt-1 text-body-sm text-muted">
              The live history table will populate when the office is filled or when transition
              records are written.
            </p>
          </div>
        )}
      </section>

      <section className="mt-8">
        <h2 className="mb-3 text-heading font-extrabold tracking-[-0.03em] text-foreground">
          Office holder history
        </h2>
        <div className="space-y-8">
          {page.tenureGroups.map((group) => (
            <div key={`${group.iteration.type}-${group.iteration.number}`}>
              <h3 className="mb-2 text-body-lg font-bold tracking-[-0.01em] text-foreground">
                {group.label}
              </h3>
              {group.entries.length > 0 ? (
                <div className="overflow-x-auto">
                  <table className="w-full min-w-[680px] text-body">
                    <thead>
                      <tr className="text-left text-body-sm font-semibold uppercase tracking-[0.06em] text-muted">
                        <th className="border-b border-card-border py-1.5 pr-4 font-semibold">
                          Holder
                        </th>
                        <th className="border-b border-card-border py-1.5 pr-4 font-semibold">
                          Party
                        </th>
                        <th className="border-b border-card-border py-1.5 pr-4 font-semibold">
                          Tenure
                        </th>
                        <th className="border-b border-card-border py-1.5 pr-4 font-semibold">
                          Dates
                        </th>
                        <th className="border-b border-card-border py-1.5 font-semibold">Source</th>
                      </tr>
                    </thead>
                    <tbody>
                      {group.entries.map((entry, index) => (
                        <tr
                          key={`${entry.name}-${entry.startWeekYear ?? entry.manualId ?? index}`}
                          className="border-b border-card-border/60 last:border-0"
                        >
                          <td className="py-2 pr-4 font-medium text-foreground">
                            {entry.profileHref ? (
                              <Link href={entry.profileHref} className="hover:text-primary">
                                {entry.name}
                              </Link>
                            ) : (
                              entry.name
                            )}
                            {entry.isCurrent && (
                              <span className="ml-2 rounded-full bg-primary/15 px-2 py-0.5 text-body-sm font-semibold text-[var(--wiki-link)]">
                                Incumbent
                              </span>
                            )}
                          </td>
                          <td className="py-2 pr-4 text-muted">
                            {entry.partyLabel ?? entry.party ?? "-"}
                          </td>
                          <td className="py-2 pr-4 font-mono text-body-sm text-muted">
                            {tenureRangeWeekYear(entry)}
                          </td>
                          <td className="py-2 pr-4 text-body-sm text-muted">
                            {realLifeDateRange(entry)}
                          </td>
                          <td className="py-2 text-muted">{entry.source.replace(/-/g, " ")}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              ) : (
                <p className="py-2 text-body-sm text-muted">No recorded holders yet.</p>
              )}
              {isAdmin && (
                <OfficeHistoryAdmin
                  officeIdentity={{
                    countryId: page.definition.countryId,
                    officeKind: page.definition.kind,
                    officeType: page.definition.officeType,
                    positionId: page.definition.positionId,
                    leadershipRole: page.definition.leadershipRole,
                  }}
                  iteration={group.iteration}
                  manualRows={group.entries
                    .filter((e) => e.isManual && e.manualId && e.manualData)
                    .map((e) => ({
                      id: e.manualId!,
                      name: e.name,
                      party: e.party,
                      startWeek: e.manualData!.startWeek,
                      startYear: e.manualData!.startYear,
                      endWeek: e.manualData!.endWeek,
                      endYear: e.manualData!.endYear,
                      startDate: e.manualData!.startDate,
                      endDate: e.manualData!.endDate,
                      isIncumbent: e.manualData!.isIncumbent,
                    }))}
                />
              )}
            </div>
          ))}
        </div>
      </section>

      <RelatedPagesFooter currentSlug={slug} currentCategory="reference" />
    </WikiArticleFrame>
  );
}

async function RelatedPagesFooter({
  currentSlug,
  currentCategory,
  currentTags,
}: {
  currentSlug: string;
  currentCategory?: string;
  currentTags?: string[];
}) {
  const allSlugs = await getAllWikiSlugsAsync();
  const candidateSlugs = allSlugs.filter((s) => s !== currentSlug && s !== "elections");
  const pageMap = await getWikiPagesBySlugs(candidateSlugs);

  const currentTagSet = new Set(currentTags ?? []);
  const currentCat = currentCategory;

  // Score each candidate: shared category = +3, shared tag = +1 each.
  // Sort by score descending, then title ascending. Take top 8.
  const scored = candidateSlugs
    .map((slug) => {
      const pageData = pageMap.get(slug);
      if (!pageData) return null;
      let score = 0;
      if (currentCat && pageData.category && pageData.category === currentCat) {
        score += 3;
      }
      if (currentTagSet.size > 0 && pageData.tags) {
        for (const tag of pageData.tags) {
          if (currentTagSet.has(tag)) score += 1;
        }
      }
      return { slug, title: pageData.title, score };
    })
    .filter((x): x is { slug: string; title: string; score: number } => x !== null)
    .sort((a, b) => {
      if (b.score !== a.score) return b.score - a.score;
      return a.title.localeCompare(b.title);
    })
    .slice(0, 8);

  return (
    <footer className="mt-10 border-t border-card-border pt-5">
      <h3 className="mb-2 text-body-lg font-semibold uppercase tracking-[0.06em] text-muted">
        Related pages
      </h3>
      <div className="flex flex-wrap gap-x-4 gap-y-1">
        {scored.map(({ slug, title }) => (
          <Link
            key={slug}
            href={`/wiki/${slug}`}
            className="text-body-sm text-[var(--wiki-link)] hover:underline"
          >
            {title}
          </Link>
        ))}
      </div>
    </footer>
  );
}
